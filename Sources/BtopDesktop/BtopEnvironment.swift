import Foundation

/// Locates the btop executable and manages the app-private btop configuration directory.
enum BtopEnvironment {
    /// ~/Library/Application Support/BtopDesktop  (passed to btop as XDG_CONFIG_HOME)
    static let configHome: URL = {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        return base.appendingPathComponent("BtopDesktop", isDirectory: true)
    }()

    static var btopConfigDir: URL { configHome.appendingPathComponent("btop", isDirectory: true) }
    static var btopConfigFile: URL { btopConfigDir.appendingPathComponent("btop.conf") }

    static let preferredThemes = ["tokyo-night", "dracula"]

    /// Finds the btop executable.
    static func locateBtop() -> String? {
        var candidates = ["/opt/homebrew/bin/btop", "/usr/local/bin/btop"]
        if let path = ProcessInfo.processInfo.environment["PATH"] {
            candidates += path.split(separator: ":").map { "\($0)/btop" }
        }
        return candidates.first { FileManager.default.isExecutableFile(atPath: $0) }
    }

    /// Environment passed to btop.
    static func processEnvironment() -> [String] {
        var env = ProcessInfo.processInfo.environment
        env["TERM"] = "xterm-256color"
        env["COLORTERM"] = "truecolor"
        env["XDG_CONFIG_HOME"] = configHome.path
        // Apps launched from Finder have no LANG, so btop cannot detect a UTF-8 locale. Provide one.
        let lang = env["LANG"] ?? ""
        if !lang.uppercased().contains("UTF-8") {
            env["LANG"] = "en_US.UTF-8"
        }
        env["LC_ALL"] = env["LANG"]
        let extraPath = "/opt/homebrew/bin:/usr/local/bin"
        env["PATH"] = env["PATH"].map { "\(extraPath):\($0)" } ?? "\(extraPath):/usr/bin:/bin"
        env.removeValue(forKey: "TERM_PROGRAM")
        return env.map { "\($0.key)=\($0.value)" }
    }

    /// Creates the app-private btop.conf if it does not exist.
    static func ensureConfig(btopPath: String) throws {
        let fm = FileManager.default
        try fm.createDirectory(at: btopConfigDir, withIntermediateDirectories: true)
        guard !fm.fileExists(atPath: btopConfigFile.path) else { return }

        // btop rewrites the config on exit when the header version differs, so write the real version.
        let version = btopVersion(btopPath: btopPath) ?? "1.4.0"
        let theme = themeValue(btopPath: btopPath)
        let conf = """
        #? Config file for btop v.\(version)

        #* Generated by BtopDesktop. This file is used only by BtopDesktop (XDG_CONFIG_HOME is redirected).
        #* Edit freely, then choose "Restart btop" from the menu bar icon.

        #* Name of a btop++/bpytop/bashtop formatted ".theme" file, "Default" and "TTY" for builtin themes.
        color_theme = "\(theme)"

        #* If the theme set background should be shown, set to False if you want terminal background transparency.
        theme_background = False

        #* Sets if 24-bit truecolor should be used, will convert 24-bit colors to 256 color (6x6x6 color cube) if false.
        truecolor = True

        #* Rounded corners on boxes, is ignored if TTY mode is ON.
        rounded_corners = True

        #* Update time in milliseconds, recommended 2000 ms or above for better sample times for graphs.
        update_ms = 1000

        #* Manually set which boxes to show. Available values are "cpu mem net proc" and "gpu0" through "gpu5", separate values with whitespace.
        shown_boxes = "cpu mem net proc"

        """
        try conf.write(to: btopConfigFile, atomically: true, encoding: .utf8)
    }

    /// Full path of the theme file (or the theme name if not found).
    /// The prefix next to bin/ is tried before the resolved Cellar path so `brew upgrade` does not break it.
    private static func themeValue(btopPath: String) -> String {
        let link = URL(fileURLWithPath: btopPath)
        let prefixes = [link, link.resolvingSymlinksInPath()].map {
            $0.deletingLastPathComponent().deletingLastPathComponent()
        }
        for prefix in prefixes {
            let dir = prefix.appendingPathComponent("share/btop/themes")
            for name in preferredThemes {
                let file = dir.appendingPathComponent("\(name).theme")
                if FileManager.default.fileExists(atPath: file.path) { return file.path }
            }
        }
        return preferredThemes[0]
    }

    private static func btopVersion(btopPath: String) -> String? {
        let p = Process()
        p.executableURL = URL(fileURLWithPath: btopPath)
        p.arguments = ["--version"]
        let pipe = Pipe()
        p.standardOutput = pipe
        p.standardError = FileHandle.nullDevice
        do { try p.run() } catch { return nil }
        let data = pipe.fileHandleForReading.readDataToEndOfFile()
        p.waitUntilExit()
        guard let out = String(data: data, encoding: .utf8),
              let range = out.range(of: #"\d+\.\d+\.\d+"#, options: .regularExpression) else { return nil }
        return String(out[range])
    }
}
